// Claude original 1권 MP4 restoration: immutable two-part source & exact text-to-audio map.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('claude-library/1_강의페이지/01_근육학/클로드_근육학_01권_어깨·견갑대.html','utf8');
const match=source.match(/<script>window\.__AUD__=(\{[\s\S]*?\});<\/script>/);
assert.ok(match,'original audio JSON assignment exists');
const original=JSON.parse(match[1]);
assert.equal(original.urls.length,2);
assert.equal(original.t.length,671);
assert.ok(original.t.every(x=>Array.isArray(x)&&x.length===3&&[0,1].includes(x[0])&&x[2]>=x[1]));
assert.equal(Math.max(...original.t.filter(x=>x[0]===0).map(x=>x[2])),4490.598);
assert.equal(Math.max(...original.t.filter(x=>x[0]===1).map(x=>x[2])),2047.270);
const js=fs.readFileSync('scripts/claude-native-muscle-recorded-audio-v1.js','utf8');
const c={window:{},console};
vm.runInNewContext(js,c);
assert.equal(typeof c.window.LYSClaudeRecordedAudio.mount,'function');
assert.equal(typeof c.window.LYSClaudeRecordedAudio.stop,'function');
const doc={querySelectorAll:()=>[{textContent:'window.__AUD__='+JSON.stringify(original)+';'}]};
const cues=c.window.LYSClaudeRecordedAudio.timing(doc);
assert.equal(cues.length,671);
assert.ok(js.includes('URL.createObjectURL(file)'));
assert.ok(js.includes("crypto.subtle.digest('SHA-256'"));
assert.ok(js.includes('sha'));
assert.ok(!js.includes('runway.com'));
assert.ok(!js.includes('fetch('));
const reg=JSON.parse(fs.readFileSync('data/claude-original-audio-recovery-muscle1-v1.json','utf8'));
assert.equal(reg.parts.length,2);
for(const row of reg.parts)assert.ok(js.includes(row.sha256));
const html=fs.readFileSync('index.html','utf8');
assert.ok(html.includes('scripts/claude-native-muscle-recorded-audio-v1.js'));
const native=fs.readFileSync('scripts/claude-native-muscle-v1.js','utf8');
assert.ok(native.includes('window.LYSClaudeRecordedAudio.mount(shadow,doc)'));
console.log('CLAUDE ORIGINAL MP4 IN-APP PILOT QA PASS | SHA-256 locked 2 local-file MP4 | 671 synced original cues | 1+2 parts full duration, no paid TTS');
