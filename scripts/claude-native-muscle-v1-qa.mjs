// Stage 24 pilot regression: canonical data cannot be silently truncated.
import assert from 'node:assert/strict';
import fs from 'node:fs';
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('scripts/claude-native-muscle-v1.js','utf8');
const css=fs.readFileSync('styles/claude-native-muscle-v1.css','utf8');
const manifest=JSON.parse(fs.readFileSync('data/claude-library-manifest-v1.json','utf8'));
const item=manifest.lectures.find(x=>x.number===3);
assert.ok(item&&item.source_bytes===1104600&&/^[0-9a-f]{64}$/.test(item.source_sha256));
const source=fs.readFileSync('claude-library/'+item.source_path,'utf8');
const verify=(regexp,count,name)=>assert.equal((source.match(regexp)||[]).length,count,name);
verify(/<section\b/g,19,'canonical 19 chapter sections');
verify(/<table\b/g,49,'canonical 49 tables');
verify(/<figure\b/g,18,'canonical 18 figures');
verify(/<img\b/g,18,'canonical 18 figures images');
verify(/\bdata-i="/g,671,'canonical 671 educational segments');
assert.ok(html.includes('<script src="./scripts/claude-native-muscle-v1.js"></script>'));
assert.ok(html.includes('styles/claude-native-muscle-v1.css'));
assert.ok(js.includes('const PILOT_NUMBER=3'));
assert.ok(js.includes('attachShadow({mode:'));
assert.ok(js.includes("crypto.subtle.digest('SHA-256',bytes)"));
assert.ok(js.includes('document.importNode(sourceWrap,true)'));
assert.ok(js.includes('addExpandedNotes(originalBody)'));
assert.ok(js.includes("window.openClaudeOriginalLecture=openPilot"));
assert.ok(js.includes("showOriginalComparison"));
assert.ok(js.includes('audio'));
assert.ok(css.includes('.claude-native-pilot'));
assert.ok(!js.includes("innerHTML=source"));
console.log('CLAUDE NATIVE MUSCLE 1 PILOT QA PASS | source 19 chapters, 49 tables, 18 figures, 671 segments; SHA gate; full DOM; additive notes; original comparison');
